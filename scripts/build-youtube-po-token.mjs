import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
const bundle = await build({ entryPoints: ["scripts/youtube-po-token-browser.mjs"], bundle: true,
  platform: "browser", format: "iife", target: "es2020", minify: true, legalComments: "none", write: false });
const license = await readFile("node_modules/bgutils-js/LICENSE", "utf8");
const script = bundle.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const html = `<!doctype html><!--\n${license}\n--><html><head><meta name="viewport" content="width=device-width,initial-scale=1"><script>${script}</script></head><body></body></html>`;
await writeFile("src/services/youtube/YouTubePoTokenHtml.ts", `// Generated by npm run youtube:build-token. BgUtils license included below.\n/*\n${license}\n*/\nexport const youtubePoTokenHtml = ${JSON.stringify(html)};\n`);
